package main

import (
	"bytes"
	"fmt"
	"sort"
	"strings"
)

// generateTypeScript produces a TypeScript declaration file containing interface contracts.
func generateTypeScript(structs []StructDoc) string {
	var buf bytes.Buffer
	buf.WriteString("/**\n")
	buf.WriteString(" * Code generated by cmd/gendocs. DO NOT EDIT.\n")
	buf.WriteString(" * Source: Go internal/models/ and internal/profiles/ AST\n")
	buf.WriteString(" */\n\n")

	// Deduplicate structs by name
	seen := make(map[string]bool)
	var unique []StructDoc
	for _, s := range structs {
		if seen[s.Name] || len(s.Fields) == 0 {
			continue
		}
		seen[s.Name] = true
		unique = append(unique, s)
	}

	sort.Slice(unique, func(i, j int) bool {
		return unique[i].Name < unique[j].Name
	})

	for _, s := range unique {
		writeTSInterface(&buf, s)
	}

	return buf.String()
}

func writeTSInterface(buf *bytes.Buffer, s StructDoc) {
	if s.Description != "" {
		buf.WriteString("/**\n")
		for _, line := range strings.Split(s.Description, "\n") {
			buf.WriteString(fmt.Sprintf(" * %s\n", strings.TrimSpace(line)))
		}
		buf.WriteString(" */\n")
	}
	buf.WriteString(fmt.Sprintf("export interface %s {\n", s.Name))
	for _, f := range s.Fields {
		if f.JSONKey == "" || f.JSONKey == "-" {
			continue
		}
		if f.Description != "" {
			cleanDesc := strings.ReplaceAll(strings.TrimSpace(f.Description), "*/", "* /")
			buf.WriteString(fmt.Sprintf("  /** %s */\n", cleanDesc))
		}
		opt := ""
		if f.IsOptional {
			opt = "?"
		}
		tsType := mapGoTypeToTS(f.Type)
		buf.WriteString(fmt.Sprintf("  %s%s: %s\n", f.JSONKey, opt, tsType))
	}
	buf.WriteString("}\n\n")
}

func mapGoTypeToTS(goType string) string {
	t := strings.TrimSpace(goType)

	// Handle pointer
	if strings.HasPrefix(t, "*") {
		return mapGoTypeToTS(strings.TrimPrefix(t, "*"))
	}

	// Handle slice/array
	if strings.HasPrefix(t, "[]") {
		elem := mapGoTypeToTS(strings.TrimPrefix(t, "[]"))
		return elem + "[]"
	}

	// Handle map
	if strings.HasPrefix(t, "map[") {
		idx := strings.Index(t, "]")
		if idx > 4 {
			keyType := mapGoTypeToTS(t[4:idx])
			valType := mapGoTypeToTS(t[idx+1:])
			return fmt.Sprintf("Record<%s, %s>", keyType, valType)
		}
		return "Record<string, any>"
	}

	// Strip package selector if any (e.g. time.Time, models.Foo)
	if strings.Contains(t, ".") {
		parts := strings.Split(t, ".")
		t = parts[len(parts)-1]
	}

	switch t {
	case "string", "CandidateCondition", "CandidateSide", "DiagnosticCheckStatus",
		"ProviderCategory", "SyncFSMState", "ProfileStatus", "ReviewMode",
		"NotificationPreference", "ActionDecision", "ReviewSessionStatus":
		return "string"
	case "int", "int8", "int16", "int32", "int64",
		"uint", "uint8", "uint16", "uint32", "uint64",
		"float32", "float64", "byte", "rune":
		return "number"
	case "bool":
		return "boolean"
	case "interface{}", "any", "RawMessage":
		return "any"
	case "Time":
		return "string"
	case "MaxDeleteValue":
		return "string | number"
	case "ProviderOptionsMap":
		return "Record<string, string | boolean | number>"
	default:
		return t
	}
}
